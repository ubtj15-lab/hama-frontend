type TurnInput = Partial<GoldTurn> & Pick<GoldTurn, "utterance" | "refinement">;

function written<T>(value: T | undefined, fallback: T): T {
  return value === undefined ? fallback : value;
}

function turn(input: TurnInput): GoldTurn {
  return {
    utterance: input.utterance,
    support: written(input.support, "supported"),
    refinement: input.refinement,
    category: written(input.category, "any"),
    region: written(input.region, "any"),
    withKids: written(input.withKids, "any"),
    scenario: written(input.scenario, "any"),
    indoor: written(input.indoor, "any"),
    distance: written(input.distance, "any"),
    calm: written(input.calm, "any"),
    parking: written(input.parking, "any"),
    notSpicy: written(input.notSpicy, "any"),
    weather: written(input.weather, "any"),
    foodSub: written(input.foodSub, "any"),
    linkedFood: input.linkedFood ?? false,
    playListKept: input.playListKept ?? false,
    clarification: input.clarification ?? false,
    excludePlaceIds: input.excludePlaceIds ?? [],
    rejectedCategories: input.rejectedCategories ?? [],
    excludeMenus: input.excludeMenus ?? [],
    recommendationMode: input.recommendationMode ?? "any",
    searchQuery: input.searchQuery,
    retain: input.retain ?? [],
    add: input.add ?? [],
    remove: input.remove ?? [],
    shownPlaces: input.shownPlaces ?? [],
    goldConfidence: input.goldConfidence ?? "firm",
    fixRoute: input.fixRoute ?? "rules",
    rejectionCase: input.rejectionCase ?? false,
    note: input.note,
  };
}

