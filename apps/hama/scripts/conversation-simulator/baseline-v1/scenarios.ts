/**
 * Human-authored gold for the first conversation-understanding run.
 * Expected labels describe what a person would want HAMA to keep, change, or ask.
 * They were not produced by calling the conversation functions.
 */

function deck(prefix: string, names: string[]): PlaceStub[] {
  return names.map((name, index) => ({ id: `${prefix}-${index + 1}`, name }));
}

